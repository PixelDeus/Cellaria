/// Направления цепочечного сдвига.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum Direction {
    Up,
    Down,
    Left,
    Right,
}

/// Спецификация сдвига: направление + количество шагов.
///
/// `broadcast: false` (по умолчанию) — обычный сдвиг: значение головки
/// перемещается ЦЕЛИКОМ в конечную точку (source+direction×steps),
/// промежуточные клетки на пути не тронуты (телепорт, не движение по
/// клеткам). `broadcast: true` — значение размножается по ВСЕМУ пути (source
/// очищается, КАЖДАЯ клетка от source+1 до конечной точки получает копию
/// значения) — путь статически известен на этапе определения правила (тот
/// же `steps`, что и у обычного сдвига), поэтому это не новый механизм для
/// статического анализа конфликтов, просто более длинный список затронутых
/// ячеек. Дальний конец подчиняется тому же `Rule::overflow`, что и обычный
/// сдвиг (Discard/Write/WriteLiteral), проверяется по пути — как только путь
/// выходит за границу решётки, дальше не размножается (монотонно по прямой).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct ShiftSpec {
    pub direction: Direction,
    pub steps: u16,
    #[serde(default)]
    pub broadcast: bool,
}

impl ShiftSpec {
    pub const fn new(direction: Direction, steps: u16) -> Self {
        Self { direction, steps, broadcast: false }
    }

    pub const fn broadcast(direction: Direction, steps: u16) -> Self {
        Self { direction, steps, broadcast: true }
    }
}

