// ChangeValue — значение изменения: литерал или ссылка на паттерн
// ============================================================================

/// Значение для записи в changes: литерал (u8), ссылка на позицию в
/// паттерне ($0, $1, ...), или арифметика над двумя такими значениями
/// (`Add`/`Sub`, рекурсивно — операнды сами `ChangeValue`, так что можно
/// строить `Add(Ref(0), Literal(1))` = "прочитанное значение + 1").
///
/// **НЕ `#[serde(untagged)]`** (раньше было, убрано как исправление
/// реального бага, не стилистическая правка) — `Literal(u8)`/`Ref(usize)`
/// оба сериализуются untagged как ГОЛОЕ число, неразличимо друг от друга:
/// `ChangeValue::Ref(3)` уходил в YAML как `"3\n"`, а обратно приходил как
/// `Literal(3)` — ЛЮБОЕ правило с `Ref` в `changes`, пройдя через
/// `Engine::snapshot()`/`from_snapshot()` (или `replay()`, который тоже
/// восстанавливает из снимка), тихо теряло смысл: вместо "скопировать
/// значение из паттерна" начинало писать буквальный литерал, равный
/// индексу ссылки. Найдено эмпирически (не угадано) при подготовке модели
/// к 1.0 — ни один property/snapshot-тест не генерировал `changes` с
/// `Ref` вообще, поэтому не ловилось раньше. Убрав `untagged`, serde
/// использует обычное внешне-тегированное представление (`{Literal: 5}`/
/// `{Ref: 3}`/...) — однозначно, без коллизий. YAML-конфиги (`config.rs`)
/// это НЕ затрагивает: `parse_change_value` парсит `changes` из
/// `serde_yaml::Value` вручную (число → `Literal`, `"$N"` → `Ref`), не
/// через derive `Deserialize` этого enum — тегирование касается ТОЛЬКО
/// внутренней сериализации снимков.
///
/// ## Examples
///
/// ```
/// use cellaria::types::ChangeValue;
///
/// let lit = ChangeValue::Literal(42);
/// let ref0 = ChangeValue::Ref(0);
/// let incremented = ChangeValue::Add(Box::new(ChangeValue::Ref(0)), Box::new(ChangeValue::Literal(1)));
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum ChangeValue {
    /// Числовой литерал, например 5.
    Literal(u8),
    /// Ссылка на позицию в паттерне (0-based), например "$0" = Ref(0).
    Ref(usize),
    /// Сумма двух значений, `u8::wrapping_add` (перенос через 255→0, та же
    /// дисциплина, что и у остального u8-арифметики в кодовой базе,
    /// например `TIE_BREAK_MODULUS`'s вращение в арбитраже) — `CellType`
    /// сам по себе просто `u8`-метка, отдельного "числового" типа с
    /// насыщением/ошибкой на переполнение модель не вводит.
    Add(Box<ChangeValue>, Box<ChangeValue>),
    /// Разность двух значений, `u8::wrapping_sub` — та же дисциплина, что и `Add`.
    Sub(Box<ChangeValue>, Box<ChangeValue>),
}

