/// Content-addressable поиск с ограниченным радиусом ("магнит"): вместо
/// сопоставления по ФИКСИРОВАННОМУ смещению (`pattern`) правило ищет
/// БЛИЖАЙШУЮ клетку типа `target_type` в диске Chebyshev-радиуса `radius`
/// вокруг клетки-головы и, если находит, притягивает её значение на место
/// головы (найденная клетка становится дефолтной, голова — `target_type`) —
/// как обычный сдвиг, но с целью, известной только в рантайме, а не на
/// этапе определения правила.
///
/// **Почему радиус, а не поиск по всей решётке:** неограниченный поиск
/// ломает статическую разрешимость конфликтов — главное свойство, ради
/// которого модель вообще выбрала решётку, а не граф (см. `paper2.md`).
/// Affected-region правила с `cam` для целей ГРАФА конфликтов (до просмотра
/// содержимого решётки) — весь диск радиуса `radius` вокруг совпадения, то
/// же консервативное огрубление, что уже использует `arbitrate_spatial`'s
/// `max_radius`. Для АРБИТРАЖА конкретного тика (`get_match_affected_cells`)
/// — уже точная найденная позиция, не весь диск (как обычный сдвиг).
///
/// Правило с `cam` не должно иметь `shifts` (притяжение — это и есть
/// единственный сдвиг правила) — см. `conflict_analyzer`/`matcher`
/// валидацию. Доказано и измерено в `examples/proof_cam_radius_search.rs`
/// (совместимость с моделью) и `examples/compare_cam_vs_wavefront.rs`
/// (выигрыш по задержке против того же эффекта, собранного обычными
/// `shifts`-правилами волновым поиском).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct CamSearch {
    /// Chebyshev-радиус поиска (|dx|.max(|dy|) ≤ radius).
    pub radius: u8,
    /// Тип искомой клетки.
    pub target_type: CellType,
}

/// Полное определение правила.
///
/// ## Examples
///
/// ```
/// use cellaria::types::{Rule, CellType, ShiftSpec, Direction, ChangeValue, OverflowAction};
///
/// let rule = Rule {
///     id: vec![CellType::new(1), CellType::new(2)],
///     pattern: vec![(0, 0, CellType::new(1)), (1, 0, CellType::new(2))],
///     shifts: vec![vec![ShiftSpec::new(Direction::Right, 1)]],
///     changes: vec![(1, 0, ChangeValue::Literal(3))],
///     active_only: false,
///     priority: 10,
///     min_age: 0,
///     overflow: OverflowAction::Discard,
///     cam: None,
///     tie_break: 0,
///     starvation_after: None,
///     feedback: None,
///     recursion: None,
///     memory: None,
///     max_activations: None, cross_layer_reads: Vec::new(),
/// };
/// assert_eq!(rule.priority, 10);
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Rule {
    /// Внутренняя область (n-кортеж CellType).
    pub id: RuleId,
    /// Двумерный паттерн для сопоставления: (dx, dy, тип).
    /// Если пуст — строится из `id` как `(dx=0..n, dy=0, id[dx])`.
    pub pattern: Vec<(i8, i8, CellType)>,
    /// Сдвиги, выполняемые правилом при срабатывании.
    ///
    /// Каждый `ShiftSpec` — независимая операция: читает исходную позицию
    /// головки (до сдвигов) и пишет её значение в свою собственную цель.
    /// Вложенность в группы (`Vec<Vec<_>>`) не влияет на применение — все
    /// сдвиги любых групп выполняются одинаково и независимо друг от друга.
    /// Поэтому правило с 2+ сдвигами — это репликация значения в несколько
    /// направлений одновременно, а не цепочка последовательных сдвигов.
    pub shifts: Vec<Vec<ShiftSpec>>,
    /// Изменения ячеек: (смещение_x, смещение_y, новое_значение).
    /// Применяются относительно КАЖДОЙ цели сдвига независимо (если сдвигов
    /// несколько — один раз на каждую); если сдвигов нет — относительно
    /// исходной позиции головки (0,0).
    pub changes: Vec<(i32, i32, ChangeValue)>,
    /// Если true — правило проверяется только в активных ячейках.
    /// Если false — проверяется везде.
    pub active_only: bool,
    /// Приоритет правила (больше = выше).
    pub priority: u32,
    /// Минимальный возраст ячейки-центра для активации правила.
    /// Правило срабатывает только если возраст ячейки ≥ min_age.
    pub min_age: u64,
    /// Действие при overflow (выходе за границу решётки).
    #[serde(default)]
    pub overflow: OverflowAction,
    /// Content-addressable поиск с ограниченным радиусом — см. [`CamSearch`].
    /// `None` (по умолчанию) — обычное правило, поведение не меняется.
    #[serde(default)]
    pub cam: Option<CamSearch>,
    /// Опциональный тай-брейк для арбитража между матчами с РАВНЫМ
    /// `priority` и равным возрастом ячейки (см. `arbitrator::arbitrate`).
    /// По умолчанию (0 у всех правил) ничего не меняет: арбитраж
    /// по-прежнему падает на `id` правила, как раньше.
    ///
    /// Если у конкурирующих правил стоят РАЗНЫЕ значения — победитель
    /// определяется как `(tie_break + generation) % TIE_BREAK_MODULUS`
    /// (см. `arbitrator::TIE_BREAK_MODULUS`) — то есть побеждает не всегда
    /// одно и то же правило (постоянное голодание при равном приоритете —
    /// иначе арбитраж падает на лексикографический порядок `id`, который
    /// НИКОГДА не меняется), а по очереди, в зависимости от текущего
    /// поколения.
    ///
    /// Частота чередования зависит от РАЗНОСТИ значений, а не от их
    /// абсолютной величины: чтобы ДВА правила чередовались строго поровну
    /// (50/50), их `tie_break` должны отличаться РОВНО на `M/2`, где
    /// `M = TIE_BREAK_MODULUS` (например, `0` и `8` при `M=16`). Для
    /// K-стороннего round-robin — на `M/K`. Соседние значения (разница в 1)
    /// чередуются, но сильно неровно — см. подробности у
    /// `arbitrator::TIE_BREAK_MODULUS`.
    #[serde(default)]
    pub tie_break: u32,
    /// Защита от голодания при РАЗНОМ приоритете (в отличие от `tie_break`,
    /// который решает только РАВНЫЙ приоритет — см. его doc-комментарий).
    /// `None` (по умолчанию) — обычное поведение: более низкий приоритет
    /// может проигрывать одному и тому же сопернику НАВСЕГДА, арбитраж не
    /// гарантирует прогресса для него.
    ///
    /// `Some(n)` — если конкретный матч (эта клетка + это правило) детектирован,
    /// но проигрывает арбитраж `n` тиков ПОДРЯД, на следующем тике его
    /// эффективный priority становится максимальным (`u32::MAX`) — гарантированно
    /// побеждает НА ЭТОТ ОДИН тик, что сбрасывает счётчик обратно в 0.
    /// Только опционально участвующие правила отслеживаются (см.
    /// `Engine::starvation_counters`) — не установлено ни у одного правила
    /// набора ⇒ нулевые накладные расходы, поведение как раньше.
    ///
    /// Доступно ТОЛЬКО через `Engine::run_tick` (нужна память МЕЖДУ тиками) —
    /// как и `Rule::cam`/самомодификация, свободная функция `run_tick`
    /// (без состояния, пересобирает кэши с нуля на каждый вызов) не может
    /// накапливать историю проигрышей, так что это поле для неё — no-op.
    #[serde(default)]
    pub starvation_after: Option<u32>,
    /// Обратная связь по результату применения — см. [`FeedbackSpec`].
    /// `None` (по умолчанию) — обычное поведение, направление сдвига
    /// неизменно.
    #[serde(default)]
    pub feedback: Option<FeedbackSpec>,
    /// Ограниченная рекурсия в пределах одного тика — см. [`RecursionSpec`].
    /// `None` (по умолчанию) — обычное поведение, правило срабатывает не
    /// более одного раза на матч.
    #[serde(default)]
    pub recursion: Option<RecursionSpec>,
    /// Память по последовательности прошлых наблюдений — см. [`MemorySpec`].
    /// `None` (по умолчанию) — обычное поведение, без дополнительного
    /// условия на историю.
    #[serde(default)]
    pub memory: Option<MemorySpec>,
    /// Бюджет срабатываний — глобальный (не по позиции, в отличие от
    /// `starvation_after`/`feedback`/`memory`) счётчик побед в арбитраже для
    /// ЭТОГО правила (`(head, rule_idx)`, см. `Engine::activation_counters`).
    /// `Some(n)` — после `n`-й победы правило перестаёт участвовать в Detect
    /// ВООБЩЕ (на любой позиции решётки) до конца симуляции — гейт-фильтр,
    /// та же точка тик-пайплайна, что и у `Rule::memory` (5.2/§4.9
    /// спецификации), читает счётчик как он был на конец ПРЕДЫДУЩЕГО тика
    /// (2.2.1); инкремент — после apply, для победителей (тот же приём, что
    /// и у `starvation_after`). `None` (по умолчанию) — без ограничения,
    /// нулевые накладные расходы.
    ///
    /// Задумано в первую очередь как страховка от неограниченного роста у
    /// `ShiftSpec::keep_source` (правило копирует, не убывая у источника —
    /// без внешнего условия завершения активные ячейки могут расти
    /// экспоненциально), но не привязано к нему структурно — применимо к
    /// любому правилу, где нужен конечный бюджет срабатываний.
    #[serde(default)]
    pub max_activations: Option<u32>,
    /// Межслойное ЧТЕНИЕ (`LayeredEngine`, многослойная решётка — стек
    /// одинаковых по размеру 2D-решёток, НЕ настоящий 3D): `(dx, dy, dz,
    /// тип)`, `dz` — смещение относительно СВОЕГО слоя к ДРУГОМУ слою (не
    /// координата, а индекс слоя-соседа; `dz=0` эквивалентно обычному
    /// `pattern`-условию на своём слое, но `pattern` и `cross_layer_reads`
    /// — РАЗНЫЕ поля намеренно, не унификация в одно: смена сигнатуры
    /// `pattern` сломала бы буквально каждую существующую конструкцию
    /// `Rule` в кодовой базе, `cross_layer_reads` — чисто аддитивное поле).
    /// Пусто (по умолчанию) — правило не читает другие слои вообще, нулевые
    /// накладные расходы, `LayeredEngine` не требуется.
    ///
    /// Первый срез НАМЕРЕННО ограничен ЧТЕНИЕМ — `changes`/`shifts` с
    /// `dz != 0` (реальное перемещение значения на другой слой) не
    /// поддерживаются, это отдельное, более сложное расширение. Условие
    /// проверяется как обычный `pattern`, но против ПРЕДТИКОВОГО состояния
    /// ЧУЖОГО слоя (та же дисциплина снимка тика 2.2.1, просто "чужой"
    /// слой тоже снимается на начало тика, не только свой). Слои без
    /// `cross_layer_reads`/`dz` между ними структурно НИКОГДА не
    /// конфликтуют по записи (запись остаётся в своём слое) — арбитраж
    /// между разными слоями не нужен вообще, каждый слой арбитрируется
    /// НЕЗАВИСИМЫМ, немодифицированным `Engine` — тот же принцип, что и у
    /// `spatial_bypass_split`, но верно по построению, а не доказывается
    /// для конкретного набора правил.
    #[serde(default)]
    pub cross_layer_reads: Vec<(i8, i8, i8, CellType)>,
}

/// Ограниченная рекурсия: правило (тот же `pattern`+`changes`, что и у
/// самого себя) повторно проверяется и применяется вдоль `direction`, до
/// `max_depth` ДОПОЛНИТЕЛЬНЫХ раз, В ПРЕДЕЛАХ ОДНОГО тика — "волна проходит
/// N клеток мгновенно", а не за N тиков. Каждый следующий уровень читает
/// уже ЗАПИСАННОЕ этим же каскадом состояние (не устаревший срез решётки
/// "до тика") — это единственное осознанное исключение из общего правила
/// "detect всегда читает pre-tick состояние": каскад целиком принадлежит
/// ОДНОМУ матчу, выигравшему арбитраж, и не может повлиять на то, что видят
/// ДРУГИЕ матчи этого же тика (они по-прежнему читают pre-tick срез).
/// Каскад останавливается на первом уровне, где `pattern`, сдвинутый на
/// `k × direction`, не совпал — так же естественно, как заливка упирается в
/// границу или несовпадающую клетку.
///
/// Ограничение: осмыслено только для правил БЕЗ сдвигов (`shifts` должно
/// быть пустым) — рекурсия расширяет эффект `changes` вдоль направления,
/// а не двигает голову; совмещать с самим сдвигом — отдельная, более
/// сложная семантика, вне текущего подмножества. Проверяется в
/// `config::load_config`.
///
/// Статическая граница для графа конфликтов (см. Лемму 4, `paper/paper4.md`
/// §8, Corollary B) — union `pattern_cells`/`changes`-ячеек, повторённых
/// для k=0..=max_depth вдоль `direction`, а не только для k=0. Точное
/// (не union) множество для КОНКРЕТНОГО матча на КОНКРЕТНОМ тике — сколько
/// уровней РЕАЛЬНО сработало — считает `applicator` по факту, тот же приём,
/// что и у CAM/`feedback`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct RecursionSpec {
    /// Максимальное число ДОПОЛНИТЕЛЬНЫХ уровней каскада (0 — эквивалентно
    /// отсутствию рекурсии, но тогда лучше просто не устанавливать поле).
    pub max_depth: u8,
    /// Направление, вдоль которого повторяется правило.
    pub direction: Direction,
}

/// Опциональная обратная связь по РЕЗУЛЬТАТУ применения: правило меняет
/// СВОЁ направление сдвига, если после `timeout` тиков подряд оно всё ещё
/// детектируется (то есть ожидаемый результат — например, целевая клетка
/// по соседству — так и не появился). Счётчик живёт в
/// `Engine::feedback_counters` (та же причина, что и у
/// `Engine::starvation_counters`: не кодировать историю через тип клетки,
/// чтобы не тратить конечное пространство `CellType` на каждый независимый
/// таймаут). См. Лемму 4 (`paper/paper4.md` §8) про то, почему смена
/// направления безопасна для статического графа конфликтов: реальная
/// зона записи правила с `feedback` — это UNION обычного (декларированного)
/// направления и `new_direction`, а не только одно из них.
///
/// В отличие от `starvation_after` (разовый boost priority, затем сброс),
/// здесь переключение — ЗАЩЁЛКА: раз сработав (счётчик достиг `timeout`),
/// `new_direction` действует ВСЕГДА для этого матча — счётчик не
/// сбрасывается. Соответствует сценарию "агент пробовал одно направление
/// N тиков, цель не нашлась — переключился насовсем", а не "разово
/// подвинулся и вернулся к прежнему поведению".
///
/// Ограничение (аналог `MAX_SHIFTS`/`MAX_CAM_RADIUS` для GPU-подмножества):
/// осмыслено только для правил РОВНО с одним сдвигом — `new_direction`
/// заменяет его целиком. Проверяется в `config::load_config`.
///
/// Важный нюанс, найденный тестом, а не сразу очевидный из дизайна: маркер
/// с `feedback` физически ДВИГАЕТСЯ каждый тик, а счётчик в
/// `Engine::feedback_counters` ключуется его ТЕКУЩЕЙ позицией — без явного
/// переноса записи счётчика на новую позицию при каждом сдвиге
/// (`applicator::apply_shift_buffered`) счётчик обнулялся бы каждый тик
/// (клетка всегда "новая"), и `timeout` никогда бы не достигался. Это уже
/// исправлено движком автоматически — пользователю API думать об этом не
/// нужно, поле документирует найденную тонкость для будущих читателей кода.
///
/// Доступно ТОЛЬКО через `Engine::run_tick` (нужна память МЕЖДУ тиками) —
/// как и `Rule::cam`/`Rule::starvation_after`, свободная функция `run_tick`
/// не хранит состояние между вызовами, так что это поле для неё — no-op.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct FeedbackSpec {
    /// Сколько тиков подряд матч должен детектироваться (независимо от
    /// исхода арбитража — считаются попытки, не поражения), прежде чем
    /// сработает переключение направления.
    pub timeout: u64,
    /// Направление сдвига после срабатывания.
    pub new_direction: Direction,
}

/// Точка и содержание записи в FIFO-буфер памяти (см. [`MemorySpec`]).
///
/// Ровно ДВЕ точки в тик-пайплайне, каждая со своим типом наблюдаемого
/// значения — не четыре независимых варианта, а один механизм (обновление
/// буфера) с двумя разными триггерами:
///
/// - `NeighborType(dir)` — ДО арбитража: что за тип у соседа в направлении
///   `dir` (относительно головы матча), прямо на детекте, независимо от
///   исхода арбитража этого тика. "Зрение": что происходит СНАРУЖИ.
/// - `RuleOutcome` — ПОСЛЕ арбитража: выиграл этот матч арбитраж в этом
///   тике или проиграл. "Самоосознание": что происходит С САМИМ правилом.
///   Тот же хук, что уже использует `Engine::starvation_counters`
///   (после арбитража Engine знает, что победило, что проиграло) — только
///   вместо скалярного счётчика в буфер кладётся один элемент за тик.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum RecordTrigger {
    /// Наблюдать тип соседа в данном направлении, на каждом тике, когда
    /// этот матч детектируется (независимо от исхода арбитража).
    NeighborType(Direction),
    /// Наблюдать исход арбитража этого матча (`Applied`/`Missed`).
    RuleOutcome,
}

/// Одно значение, хранимое в FIFO-буфере памяти — либо тип клетки
/// (для `RecordTrigger::NeighborType`), либо исход арбитража
/// (для `RecordTrigger::RuleOutcome`). Один буфер хранит значения только
/// ОДНОГО из этих вариантов — оба триггера одного правила не смешиваются,
/// у правила ровно один `record_trigger`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum RecordedValue {
    /// Тип клетки, увиденный через `NeighborType`.
    Type(CellType),
    /// Матч выиграл арбитраж в этом тике.
    Applied,
    /// Матч детектировался, но проиграл арбитраж в этом тике.
    Missed,
}

/// Память по ПОСЛЕДОВАТЕЛЬНОСТИ прошлых наблюдений — новый примитив,
/// отдельный от `starvation_after`/`feedback`: те реагируют на скалярный
/// счётчик (сколько раз подряд одно и то же), а `memory` может отличить
/// ЛЮБОЙ конкретный неоднородный паттерн (например, `[Missed, Applied,
/// Missed]`) от другого паттерна той же длины — то, что скаляр в принципе
/// не может закодировать. Правило срабатывает по обычному `pattern`, как
/// всегда, но с ДОПОЛНИТЕЛЬНЫМ условием: FIFO-буфер этого матча (см.
/// `Engine::memory_buffers`) должен точно совпадать с `match_pattern`.
///
/// Семантика гейта (v1, самая простая однозначная интерпретация):
/// буфер должен быть ПОЛНОСТЬЮ заполнен (`len() == window`) И совпадать с
/// `match_pattern` поэлементно, от старого к новому. Частичное/суффиксное
/// совпадение не поддерживается — `match_pattern.len()` должно равняться
/// `window` (проверяется в `config::load_config`).
///
/// Буфер живёт в `Engine::memory_buffers`, НЕ в типе клетки — та же причина,
/// что и у `Engine::feedback_counters`/`Engine::starvation_counters`: не
/// тратить конечное пространство `CellType` на историю, которая по своей
/// природе не является типом клетки, а внешним по отношению к решётке
/// наблюдением конкретного матча.
///
/// Гейт — это ЧИСТО runtime-фильтр кандидатов ДО арбитража: он не меняет
/// заявленную зону записи правила (`changes`/`shifts` остаются как есть),
/// поэтому Лемма 4 (`paper/paper4.md` §8) тут вообще не нужна —
/// `conflict_analyzer` не требует изменений: реальная зона записи на любом
/// тике — это подмножество того, что правило и так объявляет, гейт может
/// только СОКРАТИТЬ число реально сработавших матчей, никогда не расширить
/// зону сверх статической границы.
///
/// Ограничение на сдвиги: 0 или 1 (не больше) — если правило с `memory`
/// физически двигается, `applicator::apply_shift_buffered` обязан перенести
/// запись буфера со старой позиции на новую (тот же приём и та же причина,
/// что и `Engine::feedback_counters`'s relocation) — при БОЛЬШЕ ЧЕМ одном
/// сдвиге неоднозначно, какую из нескольких целей считать "новой позицией
/// того же концептуального маркера", поэтому это подмножество не
/// поддерживается (тот же выбор, что уже сделан для `feedback`).
/// Проверяется в `config::load_config`.
///
/// Взаимоисключение с `recursion`: уровни каскада (`applicator`'s "Фаза 3")
/// не проходят через гейт-фильтр `Engine::run_tick` (они целиком внутри
/// одного вызова `apply_rule_buffered`, без доступа к `Engine`-состоянию) —
/// комбинация тихо оставляла бы каскадные уровни негейтованными, тот же
/// класс несостыковки, что уже найден и запрещён для `recursion`+`min_age`.
/// Проверяется в `config::load_config`.
///
/// Доступно ТОЛЬКО через `Engine::run_tick` (нужна память МЕЖДУ тиками) —
/// как и `Rule::cam`/`Rule::starvation_after`/`Rule::feedback`, свободная
/// функция `run_tick` не хранит состояние между вызовами, так что это поле
/// для неё — no-op (буфер никогда не наполнится).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MemorySpec {
    /// Размер FIFO-буфера (K элементов).
    pub window: usize,
    /// Где и что записывается в буфер — см. [`RecordTrigger`].
    pub record_trigger: RecordTrigger,
    /// Целевая последовательность: гейт открыт, когда буфер полон и
    /// совпадает с этим значением поэлементно. Длина должна равняться
    /// `window` (проверяется в `config::load_config`).
    pub match_pattern: Vec<RecordedValue>,
}

