/// Направления цепочечного сдвига.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum Direction {
    Up,
    Down,
    Left,
    Right,
}

/// Спецификация сдвига: направление + количество шагов.
///
/// `broadcast: false` (по умолчанию) — обычный сдвиг: значение головки
/// перемещается ЦЕЛИКОМ в конечную точку (source+direction×steps),
/// промежуточные клетки на пути не тронуты (телепорт, не движение по
/// клеткам). `broadcast: true` — значение размножается по ВСЕМУ пути (source
/// очищается, если не задан `keep_source` — см. ниже; КАЖДАЯ клетка от
/// source+1 до конечной точки получает копию значения) — путь статически
/// известен на этапе определения правила (тот же `steps`, что и у обычного
/// сдвига), поэтому это не новый механизм для статического анализа
/// конфликтов, просто более длинный список затронутых ячеек. Дальний конец
/// подчиняется тому же `Rule::overflow`, что и обычный сдвиг
/// (Discard/Write/WriteLiteral), проверяется по пути — как только путь
/// выходит за границу решётки, дальше не размножается (монотонно по прямой).
///
/// `keep_source: false` (по умолчанию, старое поведение без изменений) —
/// исходная клетка (`source`) очищается (`Cell::default()`), как и раньше.
/// `keep_source: true` — исходная клетка НЕ трогается вообще: не входит в
/// `write_buffer`, не входит в `AffectedRegion::written_cells` (значит её
/// возраст НЕ сбрасывается — `reset_age_for_regions` работает по точному
/// списку `written_cells`, см. её doc-комментарий), значение просто
/// остаётся тем, каким было. Ортогонально `broadcast`:
/// `broadcast=false,keep_source=true` — копия в ОДНУ конечную точку без
/// перемещения ("точечное излучение"); `broadcast=true,keep_source=true`
/// ("излучение") — копия во ВСЕ клетки пути без перемещения, источник тоже
/// сохраняет значение. Разница с `broadcast`-без-`keep_source`: там значение
/// ПЕРЕМЕЩАЕТСЯ с размножением по пути (источник исчезает), здесь —
/// КОПИРУЕТСЯ (источник остаётся).
///
/// Для статического графа конфликтов (`conflict_analyzer::compute_write_cells`)
/// НИЧЕГО не меняется: исходная клетка (0,0) по-прежнему безусловно
/// включена в консервативную границу для любого правила со сдвигом — это
/// остаётся ЗДРАВЫМ (over-approximation, а не under), просто иногда чуть
/// шире необходимого, когда `keep_source=true`. Тот же приём, что уже
/// применён к CAM/`feedback`/`recursion`: точная (не union) картина нужна
/// только приложению фактического эффекта (`applicator.rs`), а не
/// одноразовому построению графа конфликтов.
///
/// GPU: `keep_source` (как и `broadcast`) вне текущего GPU-подмножества —
/// шейдер пишет только финальную точку пути, явно отказывается
/// (`GpuUnsupportedReason::KeepSourceUnsupported`), а не тихо теряет эффект.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct ShiftSpec {
    pub direction: Direction,
    pub steps: u16,
    #[serde(default)]
    pub broadcast: bool,
    #[serde(default)]
    pub keep_source: bool,
}

impl ShiftSpec {
    pub const fn new(direction: Direction, steps: u16) -> Self {
        Self { direction, steps, broadcast: false, keep_source: false }
    }

    pub const fn broadcast(direction: Direction, steps: u16) -> Self {
        Self { direction, steps, broadcast: true, keep_source: false }
    }

    /// "Излучение": как [`ShiftSpec::broadcast`] (копия во ВСЕ клетки пути),
    /// но источник НЕ очищается — значение копируется, а не перемещается.
    pub const fn emit(direction: Direction, steps: u16) -> Self {
        Self { direction, steps, broadcast: true, keep_source: true }
    }
}

